-- ============================================================================
-- WIKIDATA-CRAWLER-024 : what the step-114 entity prune will delete (dry run)
-- ============================================================================
--
-- READ ONLY. Same queries as WikidataCrawler._prune_stale_entity_rows: a target
-- entity row is an orphan when its ID_WIKIDATA has no row in the paired staging
-- table for the current batch. Run it between two crawls, after step 115 (staging
-- then holds the current batch only), to see what the next step 114 removes.
--
-- Expectations, written before the first run (2026-10-17, batch
-- wikidata_full_20261013_0817): the orphans equal the stale rows of
-- check-024-entities-in-several-tables-20261017.txt (ITEM 40 224, SERIE 11 942,
-- PERSON 1 120, MOVIE 872, CHARACTER 284, EPISODE 104, SEASON 67, 54 613 in all),
-- every SHARE under the 10 % ceiling (ENTITY_PRUNE_MAX_SHARE), STAGED > 0.
-- ============================================================================

SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SET @b = (SELECT VAR_VALUE FROM T_WC_SERVER_VARIABLE WHERE VAR_NAME = 'strwikidatacrawlercleanupbatchid');
SELECT @b AS CURRENT_BATCH;

SELECT 'A. Orphans per table, against the guard' AS SECTION;

SELECT x.ENTITY_TABLE, x.ROWS_TOTAL, x.STAGED, x.ORPHANS,
       ROUND(100 * x.ORPHANS / NULLIF(x.ROWS_TOTAL, 0), 2) AS SHARE_PCT,
       CASE WHEN x.STAGED = 0 OR x.ORPHANS > 0.10 * x.ROWS_TOTAL THEN 'REFUSED' ELSE 'ok' END AS GUARD
FROM (
    SELECT 'MOVIE' AS ENTITY_TABLE,
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_MOVIE) AS ROWS_TOTAL,
           (SELECT COUNT(*) FROM STG_T_WC_WIKIDATA_MOVIE WHERE IMPORT_BATCH_ID = @b) AS STAGED,
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_MOVIE t WHERE NOT EXISTS
               (SELECT 1 FROM STG_T_WC_WIKIDATA_MOVIE s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b)) AS ORPHANS
    UNION ALL SELECT 'SERIE',
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_SERIE),
           (SELECT COUNT(*) FROM STG_T_WC_WIKIDATA_SERIE WHERE IMPORT_BATCH_ID = @b),
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_SERIE t WHERE NOT EXISTS
               (SELECT 1 FROM STG_T_WC_WIKIDATA_SERIE s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b))
    UNION ALL SELECT 'PERSON',
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_PERSON),
           (SELECT COUNT(*) FROM STG_T_WC_WIKIDATA_PERSON WHERE IMPORT_BATCH_ID = @b),
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_PERSON t WHERE NOT EXISTS
               (SELECT 1 FROM STG_T_WC_WIKIDATA_PERSON s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b))
    UNION ALL SELECT 'ITEM',
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_ITEM),
           (SELECT COUNT(*) FROM STG_T_WC_WIKIDATA_ITEM WHERE IMPORT_BATCH_ID = @b),
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_ITEM t WHERE NOT EXISTS
               (SELECT 1 FROM STG_T_WC_WIKIDATA_ITEM s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b))
    UNION ALL SELECT 'SEASON',
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_SEASON),
           (SELECT COUNT(*) FROM STG_T_WC_WIKIDATA_SEASON WHERE IMPORT_BATCH_ID = @b),
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_SEASON t WHERE NOT EXISTS
               (SELECT 1 FROM STG_T_WC_WIKIDATA_SEASON s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b))
    UNION ALL SELECT 'EPISODE',
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_EPISODE),
           (SELECT COUNT(*) FROM STG_T_WC_WIKIDATA_EPISODE WHERE IMPORT_BATCH_ID = @b),
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_EPISODE t WHERE NOT EXISTS
               (SELECT 1 FROM STG_T_WC_WIKIDATA_EPISODE s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b))
    UNION ALL SELECT 'CHARACTER',
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_CHARACTER),
           (SELECT COUNT(*) FROM STG_T_WC_WIKIDATA_CHARACTER WHERE IMPORT_BATCH_ID = @b),
           (SELECT COUNT(*) FROM T_WC_WIKIDATA_CHARACTER t WHERE NOT EXISTS
               (SELECT 1 FROM STG_T_WC_WIKIDATA_CHARACTER s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b))
) x
ORDER BY x.ORPHANS DESC;

SELECT 'B. Ten ITEM orphans, with the table that holds them now (if any)' AS SECTION;

SELECT t.ID_WIKIDATA, t.LABEL_EN, t.TIM_UPDATED,
       COALESCE(IF(se.ID_WIKIDATA IS NOT NULL, 'SEASON', NULL), IF(c.ID_WIKIDATA IS NOT NULL, 'CHARACTER', NULL),
                IF(sr.ID_WIKIDATA IS NOT NULL, 'SERIE', NULL), IF(m.ID_WIKIDATA IS NOT NULL, 'MOVIE', NULL),
                IF(p.ID_WIKIDATA IS NOT NULL, 'PERSON', NULL), '(out of scope)') AS NOW_IN
FROM T_WC_WIKIDATA_ITEM t
LEFT JOIN T_WC_WIKIDATA_SEASON se ON se.ID_WIKIDATA = t.ID_WIKIDATA
LEFT JOIN T_WC_WIKIDATA_CHARACTER c ON c.ID_WIKIDATA = t.ID_WIKIDATA
LEFT JOIN T_WC_WIKIDATA_SERIE sr ON sr.ID_WIKIDATA = t.ID_WIKIDATA
LEFT JOIN T_WC_WIKIDATA_MOVIE m ON m.ID_WIKIDATA = t.ID_WIKIDATA
LEFT JOIN T_WC_WIKIDATA_PERSON p ON p.ID_WIKIDATA = t.ID_WIKIDATA
WHERE NOT EXISTS (SELECT 1 FROM STG_T_WC_WIKIDATA_ITEM s WHERE s.ID_WIKIDATA = t.ID_WIKIDATA AND s.IMPORT_BATCH_ID = @b)
ORDER BY t.ID_WIKIDATA
LIMIT 10;

SELECT '========== FIN ==========' AS SECTION;
