-- WIKIDATA-CRAWLER-029: which external identifiers the V2 load holds for the movies,
-- series and persons of T2S, and how well Wikidata documents budgets and box office
-- (P2130 cost, P2142 box office) with their qualifiers. Read-only. Each family query is
-- driven from the T2S table (one index lookup per entity on ID_WIKIDATA), so the
-- 16.7 M external-id rows are never scanned whole.

SELECT NOW() AS NOW_;

-- 1. External identifiers per entity type, the 60 most frequent of each family.
-- Movies and persons: the open-ended scan of the series query ran past the 600 s cap
-- on 692 763 movies and 343 859 persons (run of 2026-10-20), so these two families count
-- a chosen list of identifiers, read through the ID_PROPERTY index.
SELECT 'movie' AS FAMILY, s.ID_PROPERTY, pm.PROPERTY_LABEL,
       COUNT(*) AS STATEMENTS
FROM T_WC_WIKIDATA_STATEMENT s
INNER JOIN T_WC_T2S_MOVIE m ON m.ID_WIKIDATA = s.ID_WIKIDATA AND (m.DELETED IS NULL OR m.DELETED = 0)
LEFT JOIN T_WC_WIKIDATA_PROPERTY_METADATA pm ON pm.ID_PROPERTY = s.ID_PROPERTY
WHERE s.ID_PROPERTY IN ('P345', 'P4947', 'P11460', 'P9584', 'P1258', 'P1712', 'P6127', 'P1265', 'P2603',
                        'P480', 'P4529', 'P1237', 'P3808', 'P7299', 'P2529', 'P4282', 'P905', 'P1874',
                        'P2704', 'P8013', 'P3138', 'P12096', 'P4835', 'P8600', 'P646', 'P2671')
  AND s.DELETED = 0
GROUP BY s.ID_PROPERTY, pm.PROPERTY_LABEL
ORDER BY STATEMENTS DESC;

SELECT 'serie' AS FAMILY, s.ID_PROPERTY, pm.PROPERTY_LABEL,
       COUNT(DISTINCT t.ID_SERIE) AS ENTITIES, COUNT(*) AS VALUES_
FROM T_WC_T2S_SERIE t
INNER JOIN T_WC_WIKIDATA_STATEMENT s ON s.ID_WIKIDATA = t.ID_WIKIDATA AND s.VALUE_TYPE = 'external_id' AND s.DELETED = 0
LEFT JOIN T_WC_WIKIDATA_PROPERTY_METADATA pm ON pm.ID_PROPERTY = s.ID_PROPERTY
WHERE t.ID_WIKIDATA IS NOT NULL AND (t.DELETED IS NULL OR t.DELETED = 0)
GROUP BY s.ID_PROPERTY, pm.PROPERTY_LABEL
ORDER BY ENTITIES DESC
LIMIT 60;

SELECT 'person' AS FAMILY, s.ID_PROPERTY, pm.PROPERTY_LABEL,
       COUNT(*) AS STATEMENTS
FROM T_WC_WIKIDATA_STATEMENT s
INNER JOIN T_WC_T2S_PERSON p ON p.ID_WIKIDATA = s.ID_WIKIDATA AND (p.DELETED IS NULL OR p.DELETED = 0)
LEFT JOIN T_WC_WIKIDATA_PROPERTY_METADATA pm ON pm.ID_PROPERTY = s.ID_PROPERTY
WHERE s.ID_PROPERTY IN ('P345', 'P4985', 'P214', 'P213', 'P268', 'P244', 'P227', 'P434', 'P1953',
                        'P1266', 'P2605', 'P2387', 'P2002', 'P2003', 'P646', 'P2671', 'P6327', 'P1258',
                        'P1712', 'P2604', 'P3056')
  AND s.DELETED = 0
GROUP BY s.ID_PROPERTY, pm.PROPERTY_LABEL
ORDER BY STATEMENTS DESC;

-- 2. Family sizes, to read the counts above as a share.
SELECT 'movie' AS FAMILY, COUNT(*) AS T2S_ROWS, SUM(ID_WIKIDATA IS NOT NULL) AS WITH_QID, SUM(ID_IMDB IS NOT NULL AND ID_IMDB <> '') AS WITH_IMDB
FROM T_WC_T2S_MOVIE WHERE DELETED IS NULL OR DELETED = 0
UNION ALL
SELECT 'serie', COUNT(*), SUM(ID_WIKIDATA IS NOT NULL), SUM(ID_IMDB IS NOT NULL AND ID_IMDB <> '')
FROM T_WC_T2S_SERIE WHERE DELETED IS NULL OR DELETED = 0
UNION ALL
SELECT 'person', COUNT(*), SUM(ID_WIKIDATA IS NOT NULL), SUM(ID_IMDB IS NOT NULL AND ID_IMDB <> '')
FROM T_WC_T2S_PERSON WHERE DELETED IS NULL OR DELETED = 0;

-- 3. Budget (P2130) and box office (P2142) on T2S movies and series.
SELECT CASE WHEN m.ID_MOVIE IS NOT NULL THEN 'movie' ELSE 'serie' END AS FAMILY,
       s.ID_PROPERTY, COUNT(DISTINCT s.ID_WIKIDATA) AS ENTITIES, COUNT(*) AS STATEMENTS,
       SUM(q.AMOUNT IS NOT NULL) AS WITH_AMOUNT, COUNT(DISTINCT q.UNIT_ID_WIKIDATA) AS UNITS
FROM T_WC_WIKIDATA_STATEMENT s
INNER JOIN T_WC_WIKIDATA_QUANTITY_VALUE q ON q.ID_STATEMENT = s.ID_STATEMENT
LEFT JOIN T_WC_T2S_MOVIE m ON m.ID_WIKIDATA = s.ID_WIKIDATA
LEFT JOIN T_WC_T2S_SERIE t ON t.ID_WIKIDATA = s.ID_WIKIDATA
WHERE s.ID_PROPERTY IN ('P2130', 'P2142') AND s.DELETED = 0
  AND (m.ID_MOVIE IS NOT NULL OR t.ID_SERIE IS NOT NULL)
GROUP BY FAMILY, s.ID_PROPERTY;

-- 4. Their units (currencies), the 15 most used.
SELECT s.ID_PROPERTY, q.UNIT_ID_WIKIDATA, COUNT(*) AS STATEMENTS
FROM T_WC_WIKIDATA_STATEMENT s
INNER JOIN T_WC_WIKIDATA_QUANTITY_VALUE q ON q.ID_STATEMENT = s.ID_STATEMENT
WHERE s.ID_PROPERTY IN ('P2130', 'P2142') AND s.DELETED = 0
GROUP BY s.ID_PROPERTY, q.UNIT_ID_WIKIDATA
ORDER BY STATEMENTS DESC
LIMIT 15;

-- 5. Their qualifiers (expected: P17 country, P3005 valid in place, P585 point in time,
-- P580/P582 start/end, P1013 criterion used), with the share of statements that carry one.
SELECT s.ID_PROPERTY, sq.ID_QUALIFIER_PROPERTY, pm.PROPERTY_LABEL, sq.VALUE_TYPE,
       COUNT(DISTINCT s.ID_STATEMENT) AS STATEMENTS
FROM T_WC_WIKIDATA_STATEMENT s
INNER JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER sq ON sq.ID_STATEMENT = s.ID_STATEMENT AND sq.DELETED = 0
LEFT JOIN T_WC_WIKIDATA_PROPERTY_METADATA pm ON pm.ID_PROPERTY = sq.ID_QUALIFIER_PROPERTY
WHERE s.ID_PROPERTY IN ('P2130', 'P2142') AND s.DELETED = 0
GROUP BY s.ID_PROPERTY, sq.ID_QUALIFIER_PROPERTY, pm.PROPERTY_LABEL, sq.VALUE_TYPE
ORDER BY s.ID_PROPERTY, STATEMENTS DESC;

-- 6. Ten box office statements with their qualifiers spelled out, to see the real shape.
SELECT s.ID_WIKIDATA, s.ID_PROPERTY, s.RANK, q.AMOUNT, q.UNIT_ID_WIKIDATA,
       GROUP_CONCAT(CONCAT(sq.ID_QUALIFIER_PROPERTY, '=', COALESCE(qi.ID_ITEM, qt.RAW_TIME_VALUE, CAST(qq.AMOUNT AS CHAR), '?'))
                    ORDER BY sq.ID_QUALIFIER_PROPERTY SEPARATOR ' | ') AS QUALIFIERS
FROM T_WC_WIKIDATA_STATEMENT s
INNER JOIN T_WC_WIKIDATA_QUANTITY_VALUE q ON q.ID_STATEMENT = s.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER sq ON sq.ID_STATEMENT = s.ID_STATEMENT AND sq.DELETED = 0
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_ITEM_VALUE qi ON qi.ID_STATEMENT_QUALIFIER = sq.ID_STATEMENT_QUALIFIER
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_TIME_VALUE qt ON qt.ID_STATEMENT_QUALIFIER = sq.ID_STATEMENT_QUALIFIER
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_QUANTITY_VALUE qq ON qq.ID_STATEMENT_QUALIFIER = sq.ID_STATEMENT_QUALIFIER
WHERE s.ID_WIKIDATA IN ('Q24871', 'Q25188', 'Q44578', 'Q83495', 'Q163872')
  AND s.ID_PROPERTY IN ('P2130', 'P2142') AND s.DELETED = 0
GROUP BY s.ID_STATEMENT, s.ID_WIKIDATA, s.ID_PROPERTY, s.RANK, q.AMOUNT, q.UNIT_ID_WIKIDATA
ORDER BY s.ID_WIKIDATA, s.ID_PROPERTY, q.AMOUNT DESC
LIMIT 40;
