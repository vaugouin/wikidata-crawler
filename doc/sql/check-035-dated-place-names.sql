-- ============================================================================
-- WIKIDATA-CRAWLER-035: acceptance of the dated official names of places.
--
-- To run after the first full run carrying 1.1.28 (P1448 of cached places in a
-- Latin script, and the P580 / P582 qualifiers of their P17, P131 and P1448).
--
-- Expected:
--   A. P1448 statements exist, and P580 / P582 qualifiers exist on P17, P131
--      and P1448 statements, all on the batch of the last run.
--   B. Saint Petersburg (Q656) carries Leningrad with 1924 and 1991, Chemnitz
--      (Q2795) Karl-Marx-Stadt with 1953 and 1990.
--   C. Brno (Q14960) carries its P17 values with dates (Czechoslovakia until
--      1992, Czech Republic from 1993).
--
-- READ ONLY.
-- ============================================================================
SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;

SELECT 'A0. batch of the last run' AS CHECK_NAME, MAX(IMPORT_BATCH_ID) AS VALUE
FROM T_WC_WIKIDATA_STATEMENT WHERE ID_PROPERTY = 'P1448';

SELECT 'A1. P1448 statements, by batch' AS CHECK_NAME, IMPORT_BATCH_ID,
       COUNT(*) AS STATEMENTS, COUNT(DISTINCT ID_WIKIDATA) AS ENTITIES
FROM T_WC_WIKIDATA_STATEMENT
WHERE ID_PROPERTY = 'P1448'
GROUP BY IMPORT_BATCH_ID;

SELECT 'A2. P1448 values, by language (top 15)' AS CHECK_NAME, v.LANG_CODE, COUNT(*) AS STATEMENTS
FROM T_WC_WIKIDATA_STATEMENT s
JOIN T_WC_WIKIDATA_STRING_VALUE v ON v.ID_STATEMENT = s.ID_STATEMENT
WHERE s.ID_PROPERTY = 'P1448'
GROUP BY v.LANG_CODE
ORDER BY STATEMENTS DESC
LIMIT 15;

SELECT 'A3. dated P1448 statements (P580 or P582)' AS CHECK_NAME, q.ID_QUALIFIER_PROPERTY,
       COUNT(*) AS QUALIFIERS, COUNT(DISTINCT s.ID_STATEMENT) AS STATEMENTS,
       COUNT(DISTINCT s.ID_WIKIDATA) AS ENTITIES
FROM T_WC_WIKIDATA_STATEMENT s
JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER q ON q.ID_STATEMENT = s.ID_STATEMENT
WHERE s.ID_PROPERTY = 'P1448' AND q.ID_QUALIFIER_PROPERTY IN ('P580', 'P582')
GROUP BY q.ID_QUALIFIER_PROPERTY;

-- Limited to the three reference places: P17 and P131 hold millions of statements.
SELECT x.* FROM (
SELECT 'B. names and countries of the three reference places' AS CHECK_NAME,
       s.ID_WIKIDATA, s.ID_PROPERTY, s.`RANK`,
       COALESCE(sv.VALUE_STRING, iv.ID_ITEM) AS VALUE,
       sv.LANG_CODE,
       COALESCE(i.LABEL_EN, '') AS VALUE_LABEL_EN,
       MAX(CASE WHEN q.ID_QUALIFIER_PROPERTY = 'P580' THEN t.YEAR_VALUE END) AS START_YEAR,
       MAX(CASE WHEN q.ID_QUALIFIER_PROPERTY = 'P582' THEN t.YEAR_VALUE END) AS END_YEAR,
       s.IMPORT_BATCH_ID
FROM T_WC_WIKIDATA_STATEMENT s
LEFT JOIN T_WC_WIKIDATA_STRING_VALUE sv ON sv.ID_STATEMENT = s.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_ITEM_VALUE iv ON iv.ID_STATEMENT = s.ID_STATEMENT
LEFT JOIN T_WC_WIKIDATA_ITEM i ON i.ID_WIKIDATA = iv.ID_ITEM
LEFT JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER q
       ON q.ID_STATEMENT = s.ID_STATEMENT AND q.ID_QUALIFIER_PROPERTY IN ('P580', 'P582')
LEFT JOIN T_WC_WIKIDATA_QUALIFIER_TIME_VALUE t ON t.ID_STATEMENT_QUALIFIER = q.ID_STATEMENT_QUALIFIER
WHERE s.ID_WIKIDATA IN ('Q656', 'Q2795', 'Q14960')
  AND s.ID_PROPERTY IN ('P1448', 'P17', 'P131')
GROUP BY s.ID_STATEMENT
) x
ORDER BY x.ID_WIKIDATA, x.ID_PROPERTY, x.START_YEAR IS NULL, x.START_YEAR, x.VALUE;

SELECT 'C. verdict' AS CHECK_NAME,
  (SELECT COUNT(*) FROM T_WC_WIKIDATA_STATEMENT s
     JOIN T_WC_WIKIDATA_STRING_VALUE v ON v.ID_STATEMENT = s.ID_STATEMENT
    WHERE s.ID_WIKIDATA = 'Q656' AND s.ID_PROPERTY = 'P1448' AND v.VALUE_STRING = 'Leningrad') AS Q656_LENINGRAD,
  (SELECT COUNT(*) FROM T_WC_WIKIDATA_STATEMENT s
     JOIN T_WC_WIKIDATA_STRING_VALUE v ON v.ID_STATEMENT = s.ID_STATEMENT
    WHERE s.ID_WIKIDATA = 'Q2795' AND s.ID_PROPERTY = 'P1448' AND v.VALUE_STRING = 'Karl-Marx-Stadt') AS Q2795_KARL_MARX_STADT,
  (SELECT COUNT(DISTINCT s.ID_STATEMENT) FROM T_WC_WIKIDATA_STATEMENT s
     JOIN T_WC_WIKIDATA_STATEMENT_QUALIFIER q ON q.ID_STATEMENT = s.ID_STATEMENT
    WHERE s.ID_WIKIDATA = 'Q14960' AND s.ID_PROPERTY = 'P17'
      AND q.ID_QUALIFIER_PROPERTY IN ('P580', 'P582')) AS Q14960_DATED_P17;
